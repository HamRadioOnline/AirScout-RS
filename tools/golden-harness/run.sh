#!/usr/bin/env bash
# Regenerate golden fixtures. Uses a local dotnet SDK 8 if present, otherwise docker.
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
"$ROOT/tools/fetch-upstream.sh" >/dev/null
# ADSBDecoder.cs reads DateTime.UtcNow for pairing and GetPlanes; route it through a fake clock.
{ echo "// GENERATED by run.sh from upstream LibADSB/ADSBDecoder.cs: DateTime.UtcNow -> GoldenHarness.FakeClock.UtcNow. Do not edit."
  sed 's/DateTime\.UtcNow/GoldenHarness.FakeClock.UtcNow/g' "$ROOT/target/upstream/AirScout/LibADSB/ADSBDecoder.cs"
} > "$ROOT/tools/golden-harness/UpstreamADSBDecoder.shim.cs"
# Readsb and Dump1090 JSON DTOs: verbatim, only the shared namespace renamed so both compile side by side.
for plugin in Readsb Dump1090; do
  for f in AircraftJson AircraftListJson; do
    { echo "// GENERATED by run.sh from upstream AirScout.PlaneFeeds.Plugin.$plugin/$f.cs: namespace renamed. Do not edit."
      sed "s/namespace VirtualRadar\.Interface\.WebSite/namespace GoldenHarness.$plugin/" "$ROOT/target/upstream/AirScout/AirScout.PlaneFeeds.Plugin.$plugin/$f.cs"
    } > "$ROOT/tools/golden-harness/Upstream$plugin$f.shim.cs"
  done
done
if command -v dotnet >/dev/null 2>&1; then
  AIRSCOUT_UPSTREAM="$ROOT/target/upstream/AirScout" dotnet run --project "$ROOT/tools/golden-harness" -- "$ROOT/tests/golden"
else
  docker run --rm -v "$ROOT:/src" -w /src -e AIRSCOUT_UPSTREAM=/src/target/upstream/AirScout \
    -e DOTNET_CLI_TELEMETRY_OPTOUT=1 -e HARNESS_DEBUG -e DOTNET_NOLOGO=1 \
    mcr.microsoft.com/dotnet/sdk:8.0 \
    sh -c 'cp -r tools/golden-harness /tmp/h && rm -rf /tmp/h/bin /tmp/h/obj && dotnet run --project /tmp/h -- /src/tests/golden'
fi
